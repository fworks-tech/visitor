"""M5-7: store listing generator — pitch + style in, Play/itch listing draft out.

Generates docs/STORE_LISTING.md for a game directory: short/full
description (EN + pt-BR draft), screenshots plan, feature graphic spec,
and store-field checklist. Counts are read from the game's data files;
pass --title/--genre/--style/--pitch to override autodetection.

Usage:
    python3 listing_generator.py <game_dir> [--title T] [--genre G]
        [--style S] [--pitch P] [--out docs/STORE_LISTING.md]
"""
import argparse
import json
import sys
from pathlib import Path


def _load_json(p):
    try:
        return json.loads(Path(p).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def collect_facts(game_dir):
    """Count content + read identity from a game directory. Never throws."""
    game_dir = Path(game_dir)
    facts = {"title": game_dir.name, "genre": "narrative_choice",
             "style": "dark_horror", "pitch": "TODO: one-line hook.",
             "checkpoints": 0, "endings": 0, "visitors": 0,
             "signs": 0, "nights": 0}
    proj = game_dir / "project.godot"
    if proj.exists():
        for line in proj.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith('config/name='):
                facts["title"] = line.split("=", 1)[1].strip().strip('"')
    data = game_dir / "assets" / "data"
    story = _load_json(data / "story.json")
    if story:
        cps = story.get("checkpoints", {})
        facts["checkpoints"] = len(cps) if isinstance(cps, dict) else 0
        facts["endings"] = story.get("total_endings", 0) or 0
        nights = story.get("nights", [])
        facts["nights"] = len(nights) if isinstance(nights, list) else len(nights)
        endings = story.get("endings", [])
        n_end = len(endings) if isinstance(endings, (list, dict)) else 0
        facts["endings"] = max(facts["endings"], n_end)
        if nights:
            facts["genre"] = "fate_arbiter"
    visitors = _load_json(data / "visitors.json")
    vs = visitors.get("visitors", [])
    facts["visitors"] = len(vs) if isinstance(vs, list) else 0
    if facts["visitors"]:
        facts["genre"] = "fate_arbiter"
    signs = _load_json(data / "signs.json")
    sg = signs.get("signs", [])
    facts["signs"] = len(sg) if isinstance(sg, list) else 0
    return facts


GENRE_BLURB = {
    "narrative_choice": (
        "Every choice ripples forward across branching chapters toward "
        "multiple endings — no two playthroughs end the same way."),
    "fate_arbiter": (
        "Survivors knock. Some are human. Some only look it. "
        "Inspect, judge, live with it — LET IN, TURN AWAY, or ELIMINATE."),
}

GENRE_BLURB_PT = {
    "narrative_choice": (
        "Cada escolha reverbera pelos capítulos até múltiplos finais — "
        "nenhuma jornada termina igual à outra."),
    "fate_arbiter": (
        "Sobreviventes batem à porta. Alguns são humanos. Outros só parecem. "
        "Inspecione, julgue, conviva — ABRIGUE, DISPENSE ou ELIMINE."),
}

GENRE_SHOTS = {
    "narrative_choice": [
        "Main menu (threshold art + title)",
        "Choice moment (2-3 options visible, tension framing)",
        "Ending screen (one epilogue, no spoilers in text)",
        "Settings/pause (theme + CRT visible)",
    ],
    "fate_arbiter": [
        "Door/inspection view (visitor + sign highlight)",
        "Verdict buttons (LET IN / TURN AWAY / ELIMINATE)",
        "Night result / consequence beat",
        "Settings (CRT toggle visible)",
    ],
}


def build_listing(facts):
    """Render the full listing markdown from a facts dict."""
    g = facts["genre"] if facts["genre"] in GENRE_BLURB else "narrative_choice"
    if g == "fate_arbiter":
        scale = (f"{facts['nights']} nights, {facts['visitors']} visitors, "
                 f"{facts['signs']} signs, {facts['endings']} endings")
    else:
        scale = (f"{facts['checkpoints']} story beats, "
                 f"{facts['endings']} endings")
    shots = "\n".join(f"{i+1}. {s}" for i, s in enumerate(GENRE_SHOTS[g]))
    return f"""# Store Listing — {facts['title']}

> Generated by the DEEPTALES listing tool. Fill TODOs, then native-review
> the pt-BR draft (see Phase 7 Portuguese QA pass).
> Pitch: {facts['pitch']}

## Short description (≤ 80 chars)

TODO: one hook line. Draft: {facts['title']} — {GENRE_BLURB[g][:60 - len(facts['title'])]}…

## Full description (EN)

**{facts['title'].upper()}**

{facts['pitch']}

{GENRE_BLURB[g]}

Scale: {scale}. Hand-tuned dread: VHS/CRT grain, original synth audio,
consequence-driven story. No ads. No accounts. Your choices are the game.

Generated with DEEPTALES.

## Full description (pt-BR — DRAFT, needs native review)

**{facts['title'].upper()}**

TODO: traduzir o pitch. Draft: {facts['pitch']}

{GENRE_BLURB_PT[g]}

Escala: {scale}. Terror analógico: grão VHS/CRT, áudio sintetizado
original, história movida a consequências. Sem anúncios. Sem contas.

Gerado com DEEPTALES.

## Screenshots plan (take on-device, portrait)

{shots}
5. Feature graphic moment (door emblem + title, no UI)

## Feature graphic (1024 × 500)

Door emblem + wordmark on Void (#0A0C0B), Threshold-green accent
(#3E5C46), tagline only — no screenshots, no UI, no small text.
See docs/SHARED_BRANDING.md.

## Store fields checklist

- [ ] Category: Role Playing > Horror (Play) / Games (itch)
- [ ] Tags: horror, choices-matter, multiple-endings, analog-horror, offline, singleplayer
- [ ] Content rating questionnaire answered (horror, no gore close-ups — adjust per game)
- [ ] Data safety form: no data collected (verify: no analytics SDK in build)
- [ ] Short + full description pasted (EN done, pt-BR native-reviewed)
- [ ] 4+ screenshots + feature graphic uploaded
- [ ] Contact email + privacy policy URL (static page: \"no data collected\")
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate a store listing draft.")
    ap.add_argument("game_dir")
    for k in ("title", "genre", "style", "pitch"):
        ap.add_argument(f"--{k}", default=None)
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    facts = collect_facts(a.game_dir)
    for k in ("title", "genre", "style", "pitch"):
        v = getattr(a, k)
        if v:
            facts[k] = v
    doc = build_listing(facts)
    out = Path(a.out) if a.out else Path(a.game_dir) / "docs" / "STORE_LISTING.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(doc, encoding="utf-8")
    print(f"✓ listing → {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
